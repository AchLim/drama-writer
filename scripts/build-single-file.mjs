// Builds drama-writer.md, the single-file edition, from SKILL.md and the screenplay template.
// `--check` fails when the committed file is out of date instead of rewriting it.
import { readFileSync, writeFileSync } from "node:fs";

const read = (file) => readFileSync(file, "utf8").replace(/\r\n/g, "\n");

export function buildSingleFile() {
  const skill = read("skills/drama-writer/SKILL.md");
  const version = read("skills/drama-writer/VERSION").trim();
  const body = skill.slice(skill.indexOf("\n---\n", 4) + 5).trim();
  const withoutMap = body.slice(0, body.indexOf("\n## Reference map")).trim();
  const template = read("skills/drama-writer/templates/screenplay.md");
  const standard = template.slice(template.indexOf("## Standard"), template.indexOf("\n---\n\n## Production")).trim();

  return `<!-- Generated by scripts/build-single-file.mjs from skills/drama-writer/SKILL.md. Edit the source, then run npm run build:single. -->
# drama-writer (single-file edition, v${version})

Paste this file into a chat or a project's instructions when you can't install the full skill. It carries the workflows and the core writing rules. The full skill in [skills/drama-writer](skills/drama-writer) adds the reference guides, templates, worked examples and the runtime script that the text below mentions; without them, apply the rules here directly.

${withoutMap.replace(/^# Drama Writer\s*/, "")}

## Screenplay format

${standard.replace(/^## Standard\s*/, "")}
`;
}

const out = buildSingleFile();
if (process.argv.includes("--check")) {
  if (read("drama-writer.md") !== out) {
    console.error("drama-writer.md is out of date. Run: npm run build:single");
    process.exit(1);
  }
  console.log("drama-writer.md is up to date.");
} else {
  writeFileSync("drama-writer.md", out);
  console.log("Wrote drama-writer.md");
}
